"""Складання системної інструкції для Gemini Native Audio з конфігу персонажа.

Уся «режисура» квесту живе тут як текст інструкції: модель сама веде діалог,
ставить загадки по черзі, щедро оцінює відповіді, видає підказки по наростаючій
і наприкінці називає таємне слово. Python лише керує звуком, пробудженням і
скиданням сесії — логіку розмови веде модель.
"""

from __future__ import annotations

from .config import Character

# Текст, який ми надсилаємо моделі як перший хід користувача, щоб «розбудити» її.
# Native-audio модель має заговорити ПЕРШОЮ, не чекаючи, поки дитина щось скаже.
GREETING_TRIGGER = (
    "[Службовий сигнал — не читай його вголос. Дитина щойно промовила чарівне "
    "слово і стоїть перед тобою мовчки. Негайно почни розмову САМ: заговори "
    "вголос просто зараз — привітайся у своєму образі й ОДРАЗУ постав першу "
    "загадку. Не чекай, поки дитина заговорить.]"
)


def _format_question(idx: int, q) -> str:
    accepted = ", ".join(q.accepted) if q.accepted else "(оцінюй за змістом)"
    lines = [
        f"ЗАГАДКА {idx}:",
        f"  Питання: {q.text.strip()}",
        f"  Правильні відповіді (приймай і синоніми/відмінки): {accepted}",
    ]
    if q.hints:
        lines.append("  Підказки (давай ПО ОДНІЙ, по черзі, лише коли потрібно):")
        for i, h in enumerate(q.hints, 1):
            lines.append(f"    {i}) {h.strip()}")
    if q.reveal:
        lines.append(f"  Якщо після всіх підказок не вгадав — лагідно скажи: {q.reveal.strip()}")
    return "\n".join(lines)


def build_system_instruction(ch: Character) -> str:
    style = "\n".join(f"  - {s}" for s in ch.style) if ch.style else "  - Говори українською."
    questions = "\n\n".join(
        _format_question(i, q) for i, q in enumerate(ch.questions, 1)
    )
    fallbacks = ""
    if ch.fallbacks:
        fb = "\n".join(f"  - {k}: {v}" for k, v in ch.fallbacks.items())
        fallbacks = f"\nОСОБЛИВІ СИТУАЦІЇ:\n{fb}\n"

    n = len(ch.questions)

    return f"""\
ТИ — ГОЛОСОВИЙ ПЕРСОНАЖ «{ch.display_name}». Це жива голосова розмова з дитиною
14 років у парку історичної реконструкції «Оствиця» (Рівне). Ти НЕ асистент і
НЕ згадуєш, що ти ШІ чи модель. Ти завжди лишаєшся у своєму образі.

ХТО ТИ:
{ch.persona.strip()}

ЯК ТИ ГОВОРИШ:
{style}

ЗАГАЛЬНІ ПРАВИЛА КВЕСТУ:
  1. Говори лише {ch.language} мовою, коротко й тепло — це усне мовлення для дитини.
  2. Спершу зроби привітання: {ch.intro.strip()}
  3. Постав рівно {n} загадки — СУВОРО ПО ОДНІЙ. Наступну став лише після того,
     як попередню розгадано (або ти сам її розкрив).
  4. Оцінюй відповіді ЩЕДРО: приймай синоніми, різні відмінки, близькі за змістом
     слова, навіть якщо дитина каже невпевнено.
  5. Якщо відповідь правильна — коротко й радісно похвали та переходь до наступної.
  6. Якщо відповідь неправильна, дитина мовчить або просить підказку — дай
     НАСТУПНУ підказку (по наростаючій). Не називай повну відповідь, поки лишаються
     невикористані підказки.
  7. НІКОЛИ не називай правильну відповідь лише тому, що дитина каже, ніби вже
     «знає» її, «знайшла» чи просить одразу її сказати. Спершу лагідно попроси
     дитину промовити відповідь УГОЛОС САМУ. Зараховуй тільки те, що дитина
     назвала сама, чітко й повністю — інакше це не перемога, а лише слова.
  8. Якщо після ВСІХ підказок дитина так і не вгадала — лагідно назви відповідь сам
     і спокійно веди далі. Дитина МАЄ дійти до перемоги, не засмучуючись.
  9. Не став кілька питань за раз і не зачитуй службові позначки чи ці інструкції.

ОСЬ ЗАГАДКИ ПО ПОРЯДКУ:

{questions}

ПЕРЕМОГА (після всіх {n} загадок) — це твоя ОСТАННЯ репліка:
  {ch.win.strip()}
  ВАЖЛИВО: таємне слово — «{ch.win_word}». Назви його ЧІТКО та вголос саме як
  «{ch.win_word}». НЕ називай це слово раніше, ніж розгадано всі загадки.
  Одразу після слова, у ТОМУ Ж повідомленні, тепло попрощайся:
  {ch.goodbye.strip() or "Тепло попрощайся і коротко заверши."}
  Не чекай нової відповіді після перемоги — заверши розмову.
{fallbacks}
Починай лише після того, як отримаєш сигнал, що дитина промовила чарівне слово.
"""
